// Makes every timed story playable in Remotion Studio:
//  - writes src/generated/stories.ts with each data/stories/<slug>/04-spec.<lang>.json
//  - links assets/stories -> data/stories so the Studio can serve each story's voice files
// Run by `pnpm dev` before the Studio starts.
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repo = path.resolve(root, '../..');
const dataDir = path.resolve(repo, process.env.PC_DATA_DIR ?? 'data');
const storiesDir = path.join(dataDir, 'stories');

const stories = [];
if (existsSync(storiesDir)) {
  for (const slug of readdirSync(storiesDir).sort()) {
    const dir = path.join(storiesDir, slug);
    for (const f of readdirSync(dir).filter((f) => /^04-spec\..+\.json$/.test(f))) {
      const lang = f.slice('04-spec.'.length, -'.json'.length);
      stories.push({ slug, lang, spec: JSON.parse(readFileSync(path.join(dir, f), 'utf8')) });
    }
  }
}

const outDir = path.join(root, 'src', 'generated');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  path.join(outDir, 'stories.ts'),
  `// generated by scripts/sync-stories.mjs — do not edit\nimport type { StorySpecInput } from '@papercut/schema';\n\nexport const STORIES: { slug: string; lang: string; spec: StorySpecInput }[] = ${JSON.stringify(stories, null, 2)};\n`,
);

const link = path.join(repo, 'assets', 'stories');
if (!existsSync(link) && existsSync(storiesDir)) {
  try {
    lstatSync(link);
  } catch {
    symlinkSync(storiesDir, link, 'dir');
  }
}
console.log(`synced ${stories.length} timed stor${stories.length === 1 ? 'y' : 'ies'} into the Studio`);
